function TH_Rexxi(arr,lx,ly,rot,sc,flip,c) {
    push();
    translate(lx,ly);
    rotate(radians(rot));
    scale(sc * flip,sc);

    for (let i = 0; i < arr.length; i++) {
        for (let j = 0; j < arr[i].length; j++) {

            let a = arr[i][j];

            if (c) {
                let base;
            
                if (a === 1) base = color(232,68,68); 
                else if (a === 2) base = color(91,19,19);
                else if (a === 3) base = color(41,26,26);
                else if (a === 4) base = color(255,218,218);
                else base = color(187,169,137); // background
            
                
                let newColor = lerpColor(base, c, 0.5);
            
                fill(newColor);
            
            } else {
                if (a === 1) fill(232,68,68);
                else if (a === 2) fill(91,19,19);
                else if (a === 3) fill(41,26,26);
                else if (a === 4) fill(255,218,218);
                else continue;
            }
            rect((j * 30) + 15, (i * 30) + 15, 23, 23);
        }
    }
    pop();
};

